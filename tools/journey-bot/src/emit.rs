//! Writes the per-map tape segments and the gate journey that replays them.

use std::fmt::Write as _;
use std::path::Path;

use emulator_core::input_tape::{write_tape_poll_bound, PadSample};

use crate::obs::Obs;

/// One tape per map segment (cut at the frame that first shows the next map) and a
/// journey with an exact state checkpoint after each.
pub fn write_chain(
    out: &Path,
    state_addr: u32,
    start_poll: u64,
    samples: &[PadSample],
    boundaries: &[(String, usize, Obs)],
    finished: bool,
) {
    let dir = out.join("tapes");
    std::fs::create_dir_all(&dir).unwrap();
    let mut toml = String::new();
    writeln!(toml, "# Generated by quake-journey-bot; replays the recorded pad tapes and checks the exact state at each map change.").unwrap();
    writeln!(toml, "name = \"quake-e1-chain\"").unwrap();
    writeln!(toml, "title = \"Quake Episode 1: title to the last recorded map, one pad tape per map\"").unwrap();
    writeln!(toml, "disc = [\"build-psoxide-journey/quake-psx.cue\"]").unwrap();
    writeln!(toml, "pad = \"analog\"").unwrap();
    writeln!(toml, "max_ticks = 400000\n\n[addr]\nJOURNEY_STATE = {state_addr:#x}\n").unwrap();
    let mut from = 0usize;
    // The last segment ends where the recording does.
    let mut cuts: Vec<(String, usize, Option<&Obs>)> = boundaries
        .iter()
        .map(|(l, i, o)| (l.clone(), *i, Some(o)))
        .collect();
    // A run that stopped early (death, stall) leaves a partial tail that is not a segment.
    let _ = finished;
    if boundaries.is_empty() {
        cuts.push(("end".into(), samples.len(), None));
    }
    for (k, (label, end, obs)) in cuts.iter().enumerate() {
        let end = (*end).min(samples.len());
        if end <= from {
            continue;
        }
        let name = format!("seg-{k:02}-to-{label}.pxtape");
        write_tape_poll_bound(&dir.join(&name), &samples[from..end], if k == 0 { start_poll } else { 0 }).unwrap();
        writeln!(toml, "[[step]]\nlabel = \"pad tape to {label}\"\ntape = \"tapes/{name}\"").unwrap();
        if k > 0 {
            writeln!(toml, "tape_rebase = true").unwrap();
        }
        writeln!(toml, "timeout = {}\n", (end - from) * 4 + 4000).unwrap();
        if let Some(o) = obs {
            writeln!(toml, "[[step]]\ncheckpoint = \"{label}-loaded\"\ngolden = false").unwrap();
            writeln!(toml, "[[step.assert]]\nkind = \"not_flat\"").unwrap();
            for (word, value, what) in state_words(o) {
                writeln!(toml, "[[step.assert]]\nkind = \"ram\"\nsym = \"JOURNEY_STATE\"\noffset = {}\nsize = 4\nop = \"eq\"\nvalue = {}\nnote = \"{what}\"", word * 4, value as i64).unwrap();
            }
            writeln!(toml).unwrap();
        }
        from = end;
    }
    std::fs::write(out.join("chain.toml"), toml).unwrap();
}

/// The words a checkpoint pins: map, skill, player, inventory, counters.
fn state_words(o: &Obs) -> Vec<(usize, u32, &'static str)> {
    let mut v = vec![
        (4, o.map, "map"),
        (6, o.skill, "skill"),
        (8, o.origin[0] as u32, "origin x"),
        (9, o.origin[1] as u32, "origin y"),
        (10, o.origin[2] as u32, "origin z"),
        (19, o.health as u32, "health"),
        (20, o.armor, "armor"),
        (22, o.ammo[0], "shells"),
        (23, o.ammo[1], "nails"),
        (24, o.ammo[2], "rockets"),
        (25, o.ammo[3], "cells"),
        (26, o.weapons, "weapons"),
        (28, o.keys, "keys"),
        (30, o.kills, "kills"),
        (31, o.kills_total, "kills total"),
        (32, o.secrets, "secrets"),
        (33, o.secrets_total, "secrets total"),
    ];
    v.retain(|(_, value, _)| *value <= i32::MAX as u32 || true);
    v
}
